CREATE TABLE "Board" (
 "id" TEXT NOT NULL PRIMARY KEY, "title" TEXT NOT NULL, "goal" TEXT NOT NULL DEFAULT '',
 "sprint" TEXT NOT NULL DEFAULT '', "deadline" TEXT NOT NULL DEFAULT '', "revision" INTEGER NOT NULL DEFAULT 0,
 "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP, "updatedAt" TIMESTAMP(3) NOT NULL
);
CREATE TABLE "Column" (
 "id" TEXT NOT NULL PRIMARY KEY, "name" TEXT NOT NULL, "color" TEXT NOT NULL,
 "position" INTEGER NOT NULL, "boardId" TEXT NOT NULL REFERENCES "Board"("id") ON DELETE CASCADE ON UPDATE CASCADE
);
CREATE TABLE "Card" (
 "id" TEXT NOT NULL PRIMARY KEY, "text" TEXT NOT NULL, "priority" TEXT NOT NULL,
 "x" DOUBLE PRECISION NOT NULL, "y" DOUBLE PRECISION NOT NULL,
 "boardId" TEXT NOT NULL REFERENCES "Board"("id") ON DELETE CASCADE ON UPDATE CASCADE
);
CREATE INDEX "Column_boardId_idx" ON "Column"("boardId");
CREATE INDEX "Card_boardId_idx" ON "Card"("boardId");
